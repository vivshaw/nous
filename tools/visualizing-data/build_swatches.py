def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed sheet differs from a fresh build",
    )
    args = parser.parse_args()

    fresh = build()
    if args.check:
        current = SHEET.read_text() if SHEET.exists() else ""
        if current != fresh:
            print(
                f"{SHEET.relative_to(REPO_ROOT)} is out of date - "
                "run `uv run python tools/visualizing-data/build_swatches.py`",
                file=sys.stderr,
            )
            return 1
        print(f"{SHEET.relative_to(REPO_ROOT)} is up to date")
        return 0

    SHEET.write_text(fresh)
    print(f"wrote {SHEET.relative_to(REPO_ROOT)} ({len(fresh):,} bytes)")
    return 0


