# ---------------------------------------------------------------- chart parts
def axis_y(x0, y0, h, ticks, vmax, w):
    """Hairline gridlines plus right-aligned tick labels."""
    out = []
    for t in ticks:
        y = y0 + h - (t / vmax) * h
        out.append(f'<line class="grid" x1="{x0}" y1="{y:.1f}" x2="{x0 + w}" y2="{y:.1f}"/>')
        out.append(
            f'<text class="tick" x="{x0 - 8}" y="{y + 3.5:.1f}" text-anchor="end">{t:,}</text>'
        )
    return "\n".join(out)


def rounded_col(x, y, w, h, r=4):
    """A column with a 4px rounded data end and a square baseline end."""
    if h <= 0:
        return ""
    r = min(r, w / 2, h)
    return (
        f'<path d="M{x} {y + h} L{x} {y + r} Q{x} {y} {x + r} {y} '
        f'L{x + w - r} {y} Q{x + w} {y} {x + w} {y + r} L{x + w} {y + h} Z"/>'
    )


def rounded_bar_h(x, y, w, h, r=4):
    """A horizontal bar rounded on its right (data) end only."""
    if w <= 0:
        return ""
    r = min(r, h / 2, w)
    return (
        f'<path d="M{x} {y} L{x + w - r} {y} Q{x + w} {y} {x + w} {y + r} '
        f'L{x + w} {y + h - r} Q{x + w} {y + h} {x + w - r} {y + h} L{x} {y + h} Z"/>'
    )


