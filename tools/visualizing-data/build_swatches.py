def ramp_strip(prefix, steps):
    cells = "".join(
        f'<div class="ramp-cell" style="background:var(--{prefix}-{(i + 1) * 100})"></div>'
        for i in range(len(steps))
    )
    ticks = "".join(f"<span>{(i + 1) * 100}</span>" for i in range(len(steps)))
    return f'<div class="ramp">{cells}</div><div class="ramp-ticks">{ticks}</div>'


def div_strip():
    cells = "".join(
        f'<div class="ramp-cell" style="background:var(--viz-div-{i})"></div>' for i in range(9)
    )
    return (
        f'<div class="ramp">{cells}</div>'
        '<div class="ramp-axis"><span>more topaz</span><span>no change</span>'
        "<span>more sapphire</span></div>"
    )


def scale_legend(prefix, lo, hi, steps=7):
    cells = "".join(
        f'<i style="background:var(--{prefix}-{(i + 1) * 100})"></i>' for i in range(steps)
    )
    return (
        f'<div class="scale"><span>{lo}</span><div class="scale-strip">{cells}</div>'
        f"<span>{hi}</span></div>"
    )


