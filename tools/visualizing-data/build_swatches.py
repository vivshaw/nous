def chart_diverging():
    """Diverging bars against a zero baseline."""
    W, H = 560, 224
    x0, y0, pw = 150, 12, 340
    mid = x0 + pw / 2
    rows = [
        ("Latency p99", -18),
        ("Error rate", -7),
        ("Signups", 4),
        ("Retention", 11),
        ("Revenue", 23),
        ("Churn", -3),
    ]
    vmax = 25
    bh, gap = 22, 12
    s = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="Change against target by metric">']
    for ri, (name, v) in enumerate(rows):
        y = y0 + ri * (bh + gap)
        s.append(
            f'<text class="rowlabel" x="{x0 - 14}" y="{y + bh / 2 + 4}" '
            f'text-anchor="end">{name}</text>'
        )
        w = abs(v) / vmax * (pw / 2)
        # Index into the 9-class diverging scale: bigger magnitude sits further
        # from the neutral midpoint at index 4.
        arm = min(3, int(abs(v) / vmax * 4))
        idx = 3 - arm if v < 0 else 5 + arm
        fill = f"var(--viz-div-{idx})"
        if v < 0:
            s.append(
                f'<g fill="{fill}" transform="translate({2 * mid},0) scale(-1,1)">'
                f"{rounded_bar_h(mid, y, w - 2, bh)}</g>"
            )
            s.append(
                f'<text class="datalabel" x="{mid - w - 10:.1f}" y="{y + bh / 2 + 4}" '
                f'text-anchor="end">{v}%</text>'
            )
        else:
            s.append(f'<g fill="{fill}">{rounded_bar_h(mid + 2, y, w - 2, bh)}</g>')
            s.append(
                f'<text class="datalabel" x="{mid + w + 10:.1f}" y="{y + bh / 2 + 4}">+{v}%</text>'
            )
    s.append(
        f'<line class="axis" x1="{mid}" y1="{y0 - 4}" x2="{mid}" '
        f'y2="{y0 + len(rows) * (bh + gap) - gap + 4}"/>'
    )
    s.append("</svg>")
    return "\n".join(s)


