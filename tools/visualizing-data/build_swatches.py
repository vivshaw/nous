def chart_grouped():
    """Grouped columns, thin, capped at 24px, 2px gap between neighbours."""
    W, H = 560, 220
    x0, y0, pw, ph = 48, 12, 468, 160
    groups = ["Q1", "Q2", "Q3", "Q4"]
    series = [("Plan", 1, [180, 210, 240, 275]), ("Actual", 2, [172, 224, 231, 296])]
    vmax = 300
    s = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="Plan against actual by quarter">']
    s.append(axis_y(x0, y0, ph, [0, 100, 200, 300], vmax, pw))
    band = pw / len(groups)
    bw = min(24, (band - 24) / len(series))
    for gi, g in enumerate(groups):
        gx = x0 + gi * band + (band - (bw * len(series) + 2)) / 2
        for si, (_, slot, vals) in enumerate(series):
            h = vals[gi] / vmax * ph
            x = gx + si * (bw + 2)  # the 2px surface gap
            s.append(f'<g fill="var(--viz-{slot})">{rounded_col(x, y0 + ph - h, bw, h)}</g>')
        s.append(
            f'<text class="tick" x="{x0 + gi * band + band / 2:.1f}" y="{y0 + ph + 18}" '
            f'text-anchor="middle">{g}</text>'
        )
    s.append(f'<line class="axis" x1="{x0}" y1="{y0 + ph}" x2="{x0 + pw}" y2="{y0 + ph}"/>')
    s.append("</svg>")
    legend = "".join(
        f'<span class="key"><i class="sw" style="background:var(--viz-{slot})"></i>{n}</span>'
        for n, slot, _ in series
    )
    return "\n".join(s), legend


