def token_block(mode):
    i = 1 if mode == "light" else 2
    lines = []
    surf = CHROME[0][i]
    plane = CHROME[1][i]
    lines.append(f"  --viz-surface: {surf};")
    lines.append(f"  --viz-plane: {plane};")
    lines.append(f"  --viz-ink: {CHROME[2][i]};")
    lines.append(f"  --viz-ink-2: {CHROME[3][i]};")
    lines.append(f"  --viz-ink-muted: {CHROME[4][i]};")
    lines.append(f"  --viz-grid: {CHROME[5][i]};")
    lines.append(f"  --viz-axis: {CHROME[6][i]};")
    lines.append(f"  --viz-mute: {CHROME[7][i]};")
    for n, (_, lo, dk, _note) in enumerate(CAT, 1):
        lines.append(f"  --viz-{n}: {lo if mode == 'light' else dk};")
    ramp_a = SEQ_A_L if mode == "light" else SEQ_A_D
    ramp_t = SEQ_T_L if mode == "light" else SEQ_T_D
    for k, v in enumerate(ramp_a, 1):
        lines.append(f"  --seq-a-{k * 100}: {v};")
    for k, v in enumerate(ramp_t, 1):
        lines.append(f"  --seq-t-{k * 100}: {v};")
    for k, v in enumerate(DIV_L if mode == "light" else DIV_D):
        lines.append(f"  --viz-div-{k}: {v};")
    for name, lo, dk in STATUS:
        lines.append(f"  --viz-{name}: {lo if mode == 'light' else dk};")
    # Ink for text set *inside* a filled mark, picked by the fill's luminance.
    on = "#ffffff" if mode == "light" else CHROME[0][2]
    for n in range(1, len(CAT) + 1):
        lines.append(f"  --on-{n}: {on};")
    lines.append(f"  --on-mute: {CHROME[2][1] if mode == 'light' else '#ffffff'};")
    lines.append(f"  --track-warning: {'#fee1bf' if mode == 'light' else '#50391b'};")
    return "\n".join(lines)


